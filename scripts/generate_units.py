# Single-letter symbols that may follow a number without a space ("3m",
# "10s", "5g"); every other single letter needs the space ("5 T", "3 N",
# "2 C") so "Appendix 3C" or "plan 5N" are never units.
ATTACHABLE = frozenset("AJLVWglms%°")
# Symbols that read as English words or abbreviations in prose; a number
# before them is not enough evidence ("3 in the morning", "2 h", "5 a").
