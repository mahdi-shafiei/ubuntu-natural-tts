def load_function_names(definitions: Path) -> frozenset[str]:
    """Read MathCAT's function-name sets from its shared definitions file.

    Read with a regex rather than YAML: the ``AdditionalFunctionNames``
    block in MathCAT 0.7.7 has an unbalanced quote (``re",``).
    """
    text = definitions.read_text(encoding="utf-8")
    names: set[str] = set()
    for table in ("TrigFunctionNames", "AdditionalFunctionNames"):
        match = re.search(rf"- {table}: \{{(.*?)\n\s*\}}", text, re.S)
        if not match:
            raise SystemExit(f"table {table} not found")
        for line in match.group(1).splitlines():
            names.update(_QUOTED.findall(line.split("#", 1)[0]))
    for name in UNICODEMATHML_NAMES:
        names.update({name, "a" + name, "arc" + name, name + "h"})
    return frozenset(n for n in names if n.isalpha() and n.isascii())


def load(definitions: Path) -> dict[str, dict[str, str]]:
    """Read MathCAT's five unit tables from its YAML definitions file."""
    text = definitions.read_text(encoding="utf-8")
    # The file is a YAML list of single-key maps; duplicate keys (K and the
    # Kelvin sign) are kept by reading each block as flow mappings ourselves.
    tables: dict[str, dict[str, str]] = {}
    for name in (
        "SIPrefixes",
        "SIUnits",
        "UnitsWithoutPrefixes",
        "EnglishUnits",
        "PluralForms",
    ):
        match = re.search(rf"- {name}: \{{(.*?)\n\s*\}}", text, re.S)
        if not match:
            raise SystemExit(f"table {name} not found")
        body = "\n".join(
            line.split("#", 1)[0] if "#" in line and '"#"' not in line else line
            for line in match.group(1).splitlines()
        )
        loaded = yaml.safe_load("{" + body + "}")
        tables[name] = {str(k): str(v) for k, v in loaded.items()}
    return tables


def plural(singular: str, plurals: dict[str, str]) -> str:
    """The plural of a unit name, from the table or by the regular rule."""
    if singular in plurals:
        return plurals[singular]
    if " per " in singular:
        head, _, tail = singular.partition(" per ")
        return plural(head, plurals) + " per " + tail
    if singular.endswith(("s", "x", "z")):
        return singular
    return singular + "s"


def main(crate: Path) -> None:
    """Write the generated module from the crate checkout at ``crate``."""
    tables = load(crate / "Rules" / "Languages" / "en" / "definitions.yaml")
    version = re.search(
        r'^version = "([^"]+)"', (crate / "Cargo.toml").read_text(), re.M
    )
    plurals = {
        SPELLING.get(k, k): SPELLING.get(v, v)
        for k, v in tables["PluralForms"].items()
    }
    plurals = {k: v for k, v in plurals.items()}
    units: dict[str, tuple[str, str]] = {}
    prefixable: set[str] = set()
    for table in ("SIUnits", "UnitsWithoutPrefixes", "EnglishUnits"):
        for symbol, name in tables[table].items():
            if symbol in EXCLUDED:
                continue
            name = SPELLING.get(name, name)
            units[symbol] = (name, plural(name, plurals))
            if table == "SIUnits":
                prefixable.add(symbol)
    units.update(EXTRA)
    prefixable |= EXTRA_PREFIXABLE
    prefixes = {k: v for k, v in tables["SIPrefixes"].items()}
    prefixes["μ"] = prefixes["µ"]  # Greek mu as well as the micro sign
    label = version.group(1) if version else "?"
    names = sorted(load_function_names(crate / "Rules" / "definitions.yaml"))
    functions = Path("src/natural_tts/reading/data/functions.py")
    functions.write_text(
        FUNCTIONS_HEADER.format(version=label)
        + "FUNCTION_NAMES: frozenset[str] = frozenset(\n"
        + _sequence(names, indent=1)
        + ")\n"
    )
    out = Path("src/natural_tts/reading/data/units.py")
    body = HEADER.format(version=label)
    body += "SI_PREFIXES: dict[str, str] = " + _mapping(prefixes) + "\n"
    body += (
        "# symbol -> (singular, plural)\n"
        "UNITS: dict[str, tuple[str, str]] = " + _mapping(units) + "\n"
    )
    body += (
        "# symbols that accept an SI prefix (MathCAT's SIUnits)\n"
        "PREFIXABLE: frozenset[str] = frozenset(\n"
        + _sequence(sorted(prefixable), indent=1)
        + ")\n\n"
    )
    body += (
        "# single-letter symbols allowed directly after a number\n"
        "ATTACHABLE: frozenset[str] = frozenset(\n"
        + _sequence(sorted(ATTACHABLE), indent=1)
        + ")\n"
    )
    out.write_text(body)
    # One entry per line with trailing commas is the layout ruff keeps, so
    # the committed modules pass the formatter unchanged.
    subprocess.run(
        [sys.executable, "-m", "ruff", "format", str(out), str(functions)],
        check=True,
        capture_output=True,
    )
    print(
        f"wrote {out}: {len(units)} units, {len(prefixes)} prefixes, "
        f"{len(prefixable)} prefixable; {functions}: {len(names)} names"
    )


def _literal(value: object) -> str:
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, tuple):
        return "(" + ", ".join(_literal(v) for v in value) + ")"
    raise TypeError(type(value))


def _sequence(values: list[str], indent: int) -> str:
    pad = "    " * indent
    return "".join(f"{pad}{_literal(v)},\n" for v in values)


def _mapping(table: dict[str, object]) -> str:
    rows = "".join(
        f"    {_literal(k)}: {_literal(table[k])},\n" for k in sorted(table)
    )
    return "{\n" + rows + "}\n"


if __name__ == "__main__":
    main(Path(sys.argv[1]))
