#!/usr/bin/env python3
"""Generate ``natural_tts/reading/data/units.py`` from MathCAT's unit tables.

Source: ``Rules/Languages/en/definitions.yaml`` of the ``mathcat`` crate (MIT,
NSoiffer/MathCAT), the most complete English spoken-unit table found in the
research. The project keeps one table for prose and formulas, with NIST SP
811 spellings ("meter", "liter", "ampere") and without the symbols that are
also English words in running text ("in", "as", "am", "a", "d", "h", "y",
"w", "min" and friends), which 0.2.0 learned the hard way ("Fig. 3 in E.
coli" was read "inches"). Run from the repository root:

    python scripts/generate_units.py ~/.cargo/registry/src/*/mathcat-0.7.7

Needs PyYAML (dev extra); the output is committed, so runtime needs nothing.
"""

from __future__ import annotations

import pprint
import re
import sys
